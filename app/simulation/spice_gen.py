"""SPICE netlist generator for power rail simulation.

Produces standard SPICE3/ngspice-compatible netlists for power supply
sections of the design, including LDO and buck converter models.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from ..models.topology import Topology


class SpiceGenerator:
    """Generate SPICE netlists from a design topology."""

    def __init__(self) -> None:
        self._lines: List[str] = []

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def generate_power_netlist(
        self, topology: Topology, title: str = "Power Rail Simulation"
    ) -> str:
        """Generate a complete SPICE netlist for all power rails.

        Includes:
          - Voltage sources (input)
          - LDO behavioral models
          - Load resistors representing current draw
          - Decoupling capacitors
          - Transient analysis directive

        Args:
            topology: The design topology with power rail information.
            title: Title comment for the netlist.

        Returns:
            Complete SPICE netlist as a string.
        """
        self._lines = []
        self._comment(f"* {title}")
        self._comment(f"* Auto-generated by AutonomousHardwareArchitect-AI")
        self._comment(f"* Topology: {topology.topology_id}")
        self._blank()

        # Determine input source
        node_counter = 1

        # Generate input voltage source
        input_voltage = self._get_input_voltage(topology)
        self._comment("* === INPUT POWER SOURCE ===")
        self._line(f"V_IN vin 0 DC {input_voltage}")
        self._blank()

        # Generate each power rail
        for rail_name, rail in topology.power_rails.items():
            self._generate_rail_circuit(rail, node_counter)
            node_counter += 1

        # Analysis directives
        self._blank()
        self._comment("* === ANALYSIS ===")
        self._line(".tran 10u 10m")          # 10µs step, 10ms duration
        self._line(".op")                     # operating point
        self._blank()

        # Control block for ngspice
        self._comment("* === CONTROL ===")
        self._line(".control")
        self._line("run")
        self._line("plot v(vin) v(vout_3v3) v(vout_5v)")
        self._line("print all")
        self._line(".endc")
        self._blank()
        self._line(".end")

        return "\n".join(self._lines)

    def generate_decoupling_analysis(
        self,
        capacitor_values: List[float],
        esr_values: List[float],
        load_current_a: float,
        supply_voltage: float,
    ) -> str:
        """Generate a SPICE netlist for decoupling capacitor analysis.

        Models the supply rail with capacitors and ESR to analyze
        voltage ripple under transient load.

        Args:
            capacitor_values: Capacitance values in Farads.
            esr_values: Equivalent series resistance in Ohms.
            load_current_a: Load current in Amps.
            supply_voltage: DC supply voltage.

        Returns:
            SPICE netlist string.
        """
        self._lines = []
        self._comment("* Decoupling Capacitor Analysis")
        self._blank()

        # Ideal voltage source
        self._line(f"V1 vsupply 0 DC {supply_voltage}")

        # Source impedance
        self._line("R_src vsupply vdd 0.1")

        # Decoupling caps with ESR
        for i, (cap, esr) in enumerate(zip(capacitor_values, esr_values), 1):
            node_mid = f"n_cap{i}"
            self._line(f"R_esr{i} vdd {node_mid} {esr}")
            self._line(f"C{i} {node_mid} 0 {cap}")

        # Transient load (current pulse)
        self._line(
            f"I_load vdd 0 PULSE(0 {load_current_a} 1m 100n 100n 500u 1m)"
        )

        self._blank()
        self._line(".tran 1u 5m")
        self._line(".end")

        return "\n".join(self._lines)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------
    def _generate_rail_circuit(
        self, rail: Any, idx: int
    ) -> None:
        """Generate SPICE subcircuit for a single power rail."""
        rail_name = rail.name.replace("+", "").replace(".", "v").lower()
        out_node = f"vout_{rail_name}"

        self._comment(f"* === RAIL: {rail.name} ({rail.voltage}V) ===")

        # Model regulator as behavioral voltage source with current limit
        self._line(
            f"B_{rail_name} {out_node} 0 V={rail.voltage} "
            f"* max_I={rail.max_current_ma}mA"
        )

        # Output decoupling (generic 10µF + 100nF)
        self._line(f"C_{rail_name}_bulk {out_node} 0 10u")
        self._line(f"C_{rail_name}_dec {out_node} 0 100n")

        # Load resistor representing total current draw
        if rail.total_load_ma > 0:
            r_load = rail.voltage / (rail.total_load_ma / 1000.0)
            self._line(f"R_{rail_name}_load {out_node} 0 {r_load:.1f}")
            self._comment(
                f"*   Load: {rail.total_load_ma:.1f}mA "
                f"({len(rail.consumers)} consumers)"
            )

        self._blank()

    def _get_input_voltage(self, topology: Topology) -> float:
        """Determine the input voltage for the design."""
        # Look for the highest voltage rail as the input
        max_v = 5.0  # default USB
        for rail in topology.power_rails.values():
            if rail.voltage > max_v:
                max_v = rail.voltage
        # Input should be higher than the highest rail
        if max_v <= 5.0:
            return 5.0
        return max_v + 2.0  # headroom

    def _comment(self, text: str) -> None:
        self._lines.append(text)

    def _line(self, text: str) -> None:
        self._lines.append(text)

    def _blank(self) -> None:
        self._lines.append("")
